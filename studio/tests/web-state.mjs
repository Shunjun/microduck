import {strict as assert} from 'node:assert';
import {readFile,mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {pathToFileURL} from 'node:url';
const dir=await mkdtemp(`${tmpdir()}/studio-web-test-`);
try{
  for(const name of ['control','state','ui','preview','media'])await writeFile(`${dir}/${name}.js`,await readFile(new URL(`../web/${name}.js`,import.meta.url)));
  await writeFile(`${dir}/package.json`,'{"type":"module"}');
  const {velocityFor,controlSource,quickActions,setPreviewMode}=await import(pathToFileURL(`${dir}/control.js`));
  const {preferences}=await import(pathToFileURL(`${dir}/state.js`));
  const {bodyOrientation,skeletonPoses,Preview}=await import(pathToFileURL(`${dir}/preview.js`));
  const healthy={imu:{ready:true,missing:false,consecutive_stale_blocks:0}};
  const measured={imu:{quat:[2,0,0,0]}};
  assert.deepEqual(bodyOrientation(measured,healthy,true),[1,0,0,0]);
  for(const quat of [[0,0,0,0],[NaN,0,0,1],[1,2],['1',0,0,0]])assert.equal(bodyOrientation({imu:{quat}},healthy,true),null);
  assert.equal(bodyOrientation(measured,healthy,false),null);
  assert.equal(bodyOrientation(measured,{imu:{ready:false}},true),null);
  assert.equal(bodyOrientation(measured,{imu:{ready:true,missing:true}},true),null);
  assert.equal(bodyOrientation(measured,{imu:{ready:true,consecutive_stale_blocks:25}},true),null);
  const identity=[1,0,0,0],roll=[Math.SQRT1_2,Math.SQRT1_2,0,0];
  const model={bodies:[{parent:-1,joint:-1,p:[0,0,.12],q:identity},{parent:0,joint:0,p:[0,0,1],q:identity,axis:[0,0,1]}]};
  const poses=skeletonPoses(model,[Math.PI/2],roll);
  assert.deepEqual(poses[0].p,[0,0,.12]);
  assert.ok(Math.abs(poses[1].p[1]+1)<1e-12);
  assert.ok(Math.abs(poses[1].p[2]-.12)<1e-12);
  assert.ok(poses[1].q.every((value,i)=>Math.abs(value-[.5,.5,-.5,.5][i])<1e-12));
  const preview={orientation:roll,draw(){}};
  Preview.prototype.pose.call(preview,[1],null);
  assert.deepEqual(preview.orientation,roll);
  Preview.prototype.reset.call(preview);
  assert.deepEqual(preview.orientation,roll);
  assert.deepEqual(skeletonPoses(model,[0])[0].q,identity);

  assert.equal(controlSource({move:{source:'studio',limited_by:['deadman']}},true),null);
  assert.equal(controlSource({move:{source:'studio',limited_by:[]}},true),'studio');
  assert.equal(controlSource({move:{source:'padd'}},false),null);
  const configured={skills:[{name:'roulade'},{name:'kick_left'}],built_in:[]};
  assert.deepEqual(quickActions(configured,{enabled:true,skills:[]}),[]);
  assert.deepEqual(quickActions(configured,{enabled:false,skills:['roulade']}),[]);
  assert.deepEqual(quickActions(configured,{enabled:true,skills:['kick_left']}),[{name:'kick_left',label:'左脚踢球'}]);
  assert.deepEqual(quickActions({built_in:['sit_toggle']},{enabled:true,skills:['custom-bow']}),[{name:'custom-bow',label:'custom-bow'},{name:'sit_toggle',label:'坐下 / 起立'}]);
  const elements=new Map(['#live-pose','#live-video','.camera-empty','.cambottom','.subtabs .tail'].map(key=>[key,{}]));
  const root={querySelector:key=>elements.get(key)};
  setPreviewMode(root,'camera');
  assert.equal(elements.get('.cambottom').hidden,true);
  assert.equal(elements.get('#live-pose').hidden,true);
  assert.equal(elements.get('#live-video').hidden,false);
  assert.equal(elements.get('.subtabs .tail').textContent,'摄像头实时画面');
  setPreviewMode(root,'pose');
  assert.equal(elements.get('.cambottom').hidden,false);
  assert.equal(elements.get('#live-video').hidden,true);
  const prefs={forward:.2,turn:1};
  assert.deepEqual(velocityFor(0,-1,50,prefs),{vx:.1,vy:0,vyaw:-0});
  assert.equal(velocityFor(0,-.5,50,prefs).vx,.05);
  assert.equal(velocityFor(0,-1,0,prefs).vx,0);
  assert.equal(velocityFor(1,0,100,prefs).vyaw,-1);
  const diagonal=velocityFor(1,-1,100,prefs);assert.ok(diagonal.vx<.2&&diagonal.vyaw> -1);
  globalThis.localStorage={getItem:()=>'{"speed":0,"forward":999,"turn":999}'};
  assert.deepEqual(preferences(),{speed:0,forward:.5,turn:2});
  globalThis.localStorage={getItem:()=>'{bad'};assert.equal(preferences().speed,35);
  console.log('PASS: joystick, preview mode, loaded actions, IMU validation, root/joint transforms and camera reset');
}finally{await rm(dir,{recursive:true,force:true});}
